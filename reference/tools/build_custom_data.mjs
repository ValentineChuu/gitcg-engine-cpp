// Build @gi-tcg/data from Piovium's source (pinned tag) with our own definitions from reference/custom_data/,
// then install the result over node_modules/@gi-tcg/data/dist.
// Usage: npm run build:data

import { execFileSync } from "node:child_process";
import { cpSync, existsSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const PIOVIUM_TAG = "v0.21.0";
const PIOVIUM_REPOSITORY = "https://github.com/piovium/genius-invokation.git";
const CUSTOM_FOLDER_NAME = "autogitcg";

const engineDirectory = join(dirname(fileURLToPath(import.meta.url)), "..");
const piovium = join(engineDirectory, "piovium");
const dataPackage = join(piovium, "packages", "data");
const customSource = join(engineDirectory, "custom_data");
const customTarget = join(dataPackage, "src", CUSTOM_FOLDER_NAME);

function run(command, args, options = {}) {
  execFileSync(command, args, { stdio: "inherit", ...options });
}

function findPnpm() {
  const candidates = [
    process.env.PNPM_BINARY,
    join(engineDirectory, "..", "node_modules", "@pnpm", `exe.${process.platform}-${process.arch}`, "pnpm"),
  ].filter(Boolean);
  const found = candidates.find((candidate) => existsSync(candidate));
  if (!found) throw new Error("pnpm 12 not found: run `npm install` in engine/ or set PNPM_BINARY");
  return found;
}

function gtsFiles(directory) {
  return readdirSync(directory).flatMap((name) => {
    const path = join(directory, name);
    if (statSync(path).isDirectory()) return gtsFiles(path);
    return name.endsWith(".gts") ? [path] : [];
  });
}

if (!existsSync(piovium)) {
  run("git", ["clone", "--depth", "1", "--branch", PIOVIUM_TAG, PIOVIUM_REPOSITORY, piovium]);
}
const checkedOutTag = execFileSync("git", ["-C", piovium, "describe", "--tags", "--exact-match"]).toString().trim();
if (checkedOutTag !== PIOVIUM_TAG) throw new Error(`reference/piovium is at ${checkedOutTag}, expected ${PIOVIUM_TAG}`);

// Sync our definitions into the data package and list them in its index (generated by Piovium as "DO NOT EDIT").
rmSync(customTarget, { recursive: true, force: true });
cpSync(customSource, customTarget, { recursive: true });
run("git", ["-C", piovium, "checkout", "--", "packages/data/src/index.ts"]);
const indexPath = join(dataPackage, "src", "index.ts");
const customImports = gtsFiles(customTarget)
  .map((path) => `import "./${relative(join(dataPackage, "src"), path).replaceAll("\\", "/")}";`)
  .sort()
  .join("\n");
const exportLine = 'export * from "./end.ts";';
const index = readFileSync(indexPath, "utf8");
if (!index.includes(exportLine)) throw new Error("unexpected Piovium index.ts layout");
writeFileSync(indexPath, index.replace(exportLine, `${customImports}\n\n${exportLine}`));

const pnpm = findPnpm();
const environment = { ...process.env, PATH: `${dirname(pnpm)}:${process.env.PATH}` };
// Piovium packages the data package depends on only need building once; rebuilding them each time
// re-runs `buf generate`, which calls buf.build over the network and gets rate-limited.
const DEPENDENCY_PACKAGES = ["config", "typings", "utils", "core", "assets-manager"];
const dependenciesBuilt = DEPENDENCY_PACKAGES.every((name) => existsSync(join(piovium, "packages", name, "dist")));
run(pnpm, ["install", "--filter", "@gi-tcg/data..."], { cwd: piovium, env: environment });
run(pnpm, ["--filter", dependenciesBuilt ? "@gi-tcg/data" : "@gi-tcg/data...", "build"], { cwd: piovium, env: environment });

const installedDist = join(engineDirectory, "..", "node_modules", "@gi-tcg", "data", "dist");
rmSync(installedDist, { recursive: true, force: true });
cpSync(join(dataPackage, "dist"), installedDist, { recursive: true });
console.log(`installed @gi-tcg/data built from ${PIOVIUM_TAG} with ${gtsFiles(customSource).length} custom files`);
